-- ==============================================================================
-- SUPABASE SCHEMA: Social Accounts Automation Registry
-- Run this in your Supabase Dashboard: SQL Editor -> New Query -> Run
-- ==============================================================================

create table if not exists public.social_accounts (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  platform text not null,                  -- 'INSTAGRAM', 'FACEBOOK', 'METRICOOL'
  email text unique not null,              -- Unique constraint for auto-upsert
  username text,
  password text,
  profile_url text,
  full_mail_string text,                   -- email|pass|refreshToken|clientId
  two_factor_secret text,                  -- Base32 TOTP secret key
  backup_codes text,                       -- Emergency backup codes
  proxy text,                              -- Exit IP / proxy used
  status text default 'ACTIVE',            -- 'ACTIVE', 'SUSPENDED', 'CHECKPOINT'
  details jsonb default '{}'::jsonb        -- Hardware fingerprint, DOB, full name, etc.
);

-- Enable Row Level Security (RLS)
alter table public.social_accounts enable row level security;

-- Drop policy if exists then recreate
drop policy if exists "Enable full access for authenticated and backend keys" on public.social_accounts;
create policy "Enable full access for authenticated and backend keys"
  on public.social_accounts
  for all
  using (true)
  with check (true);

-- Grant privileges to roles
grant usage on schema public to postgres, anon, authenticated, service_role;
grant all privileges on table public.social_accounts to postgres, anon, authenticated, service_role;
grant all privileges on all sequences in schema public to postgres, anon, authenticated, service_role;

-- Index on email and platform for instant lookups
create index if not exists idx_social_accounts_email on public.social_accounts (email);
create index if not exists idx_social_accounts_platform on public.social_accounts (platform);

-- ==============================================================================
-- 2. SEPARATE TABLE: Email Accounts & Mailboxes Registry
-- ==============================================================================

create table if not exists public.email_accounts (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  email text unique not null,              -- Unique constraint (lowercase)
  password text,                           -- Mailbox password
  refresh_token text,                      -- MS / Google OAuth2 refresh token
  client_id text,                          -- OAuth2 client ID
  full_mail_string text,                   -- email|password|refresh_token|client_id
  provider text default 'outlook',         -- 'outlook', 'gmail', 'temp-mail', etc.
  status text default 'ACTIVE',            -- 'ACTIVE', 'SUSPENDED', 'USED'
  used_in_platforms text[] default '{}',   -- Array of platforms, e.g. {'facebook', 'metricool'}
  last_used_platform text,                 -- Most recent platform that used this mailbox
  last_used_at timestamptz default now(),  -- Last activity timestamp
  details jsonb default '{}'::jsonb        -- Proxy used, recovery email, etc.
);

-- Enable Row Level Security (RLS)
alter table public.email_accounts enable row level security;

-- Drop policy if exists then recreate
drop policy if exists "Enable full access for authenticated and backend keys on emails" on public.email_accounts;
create policy "Enable full access for authenticated and backend keys on emails"
  on public.email_accounts
  for all
  using (true)
  with check (true);

-- Grant privileges to roles
grant usage on schema public to postgres, anon, authenticated, service_role;
grant all privileges on table public.email_accounts to postgres, anon, authenticated, service_role;
grant all privileges on all sequences in schema public to postgres, anon, authenticated, service_role;

-- Index on email, status, and provider
create index if not exists idx_email_accounts_email on public.email_accounts (email);
create index if not exists idx_email_accounts_status on public.email_accounts (status);
create index if not exists idx_email_accounts_provider on public.email_accounts (provider);
