-- SUPABASE SCHEMA: Social Accounts Automation Registry
-- Run this in your Supabase Dashboard: SQL Editor -> New Query -> Run
-- ==============================================================================

create table if not exists public.social_accounts (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  platform text not null,                  -- 'INSTAGRAM', 'FACEBOOK', 'METRICOOL'
  email text unique not null,              -- Unique constraint for auto-upsert
  username text,
  password text,
  profile_url text,
  full_mail_string text,                   -- email|pass|refreshToken|clientId
  two_factor_secret text,                  -- Base32 TOTP secret key
  backup_codes text,                       -- Emergency backup codes
  proxy text,                              -- Exit IP / proxy used
  status text default 'ACTIVE',            -- 'ACTIVE', 'SUSPENDED', 'CHECKPOINT'
  details jsonb default '{}'::jsonb        -- Hardware fingerprint, DOB, full name, etc.
);

-- Enable Row Level Security (RLS)
alter table public.social_accounts enable row level security;

-- Drop policy if exists then recreate
drop policy if exists "Enable full access for authenticated and backend keys" on public.social_accounts;
create policy "Enable full access for authenticated and backend keys"
  on public.social_accounts
  for all
  using (true)
  with check (true);

-- Grant privileges to roles
grant usage on schema public to postgres, anon, authenticated, service_role;
grant all privileges on table public.social_accounts to postgres, anon, authenticated, service_role;
grant all privileges on all sequences in schema public to postgres, anon, authenticated, service_role;

-- Index on email and platform for instant lookups
create index if not exists idx_social_accounts_email on public.social_accounts (email);
create index if not exists idx_social_accounts_platform on public.social_accounts (platform);

-- ==============================================================================
-- 2. SEPARATE TABLE: Email Accounts & Mailboxes Registry
-- ==============================================================================

create table if not exists public.email_accounts (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  email text unique not null,              -- Unique constraint (lowercase)
  password text,                           -- Mailbox password
  refresh_token text,                      -- MS / Google OAuth2 refresh token
  client_id text,                          -- OAuth2 client ID
  full_mail_string text,                   -- email|password|refresh_token|client_id
  provider text default 'outlook',         -- 'outlook', 'gmail', 'temp-mail', etc.
  status text default 'ACTIVE',            -- 'ACTIVE', 'SUSPENDED', 'USED'
  used_in_platforms text[] default '{}',   -- Array of platforms, e.g. {'facebook', 'metricool'}
  last_used_platform text,                 -- Most recent platform that used this mailbox
  last_used_at timestamptz default now(),  -- Last activity timestamp
  details jsonb default '{}'::jsonb        -- Proxy used, recovery email, etc.
);

-- Enable Row Level Security (RLS)
alter table public.email_accounts enable row level security;

-- Drop policy if exists then recreate
drop policy if exists "Enable full access for authenticated and backend keys on emails" on public.email_accounts;
create policy "Enable full access for authenticated and backend keys on emails"
  on public.email_accounts
  for all
  using (true)
  with check (true);

-- Grant privileges to roles
grant usage on schema public to postgres, anon, authenticated, service_role;
grant all privileges on table public.email_accounts to postgres, anon, authenticated, service_role;
grant all privileges on all sequences in schema public to postgres, anon, authenticated, service_role;

-- Index on email, status, and provider
create index if not exists idx_email_accounts_email on public.email_accounts (email);
create index if not exists idx_email_accounts_status on public.email_accounts (status);
create index if not exists idx_email_accounts_provider on public.email_accounts (provider);

-- ==============================================================================
-- 3. VIDEO REGISTRY & MOVIE RECAP PIPELINE INDEX
-- ==============================================================================

create table if not exists public.video_registry (
  id bigint generated by default as identity primary key,
  video_id text unique not null,
  source_url text,
  platform text default 'douyin',
  channel text,
  batch text,
  original_filename text,
  local_path text,
  final_filename text,
  drive_filename text,
  title text,
  description text,
  tags text,
  target_language text,
  tts_engine text,
  duration_sec double precision,
  status text not null default 'downloaded',
  drive_folder text,
  drive_path text,
  drive_file_id text,
  drive_link text,
  thumbnail_path text,
  thumbnail_link text,
  metadata_json text,
  movie_id bigint,
  movie_name text,
  movie_year integer,
  movie_genre text,
  movie_synopsis text,
  movie_context text,
  movie_source text,
  movie_source_url text,
  error text,
  created_at timestamptz not null default timezone('utc'::text, now()),
  updated_at timestamptz not null default timezone('utc'::text, now()),
  uploaded_at timestamptz
);

create unique index if not exists idx_video_registry_video_id on public.video_registry (video_id);
create index if not exists idx_video_registry_status on public.video_registry (status);
create index if not exists idx_video_registry_channel on public.video_registry (channel);
create index if not exists idx_video_registry_final_filename on public.video_registry (final_filename);
create index if not exists idx_video_registry_movie_name on public.video_registry (movie_name);

create table if not exists public.registry_movies (
  id bigint generated by default as identity primary key,
  movie_key text unique not null,
  movie_name text not null,
  movie_year integer,
  movie_genre text,
  movie_synopsis text,
  movie_context text,
  movie_source text,
  movie_source_url text,
  created_at timestamptz not null default timezone('utc'::text, now()),
  updated_at timestamptz not null default timezone('utc'::text, now())
);

create unique index if not exists idx_registry_movies_key on public.registry_movies (movie_key);
create index if not exists idx_registry_movies_name on public.registry_movies (movie_name);

create table if not exists public.registry_events (
  id bigint generated by default as identity primary key,
  video_id text not null,
  event text not null,
  detail text,
  created_at timestamptz not null default timezone('utc'::text, now())
);

create index if not exists idx_registry_events_video_id on public.registry_events (video_id);

-- Enable RLS
alter table public.video_registry enable row level security;
alter table public.registry_movies enable row level security;
alter table public.registry_events enable row level security;

-- Policies
drop policy if exists "Enable full access for video_registry" on public.video_registry;
create policy "Enable full access for video_registry"
  on public.video_registry for all using (true) with check (true);

drop policy if exists "Enable full access for registry_movies" on public.registry_movies;
create policy "Enable full access for registry_movies"
  on public.registry_movies for all using (true) with check (true);

drop policy if exists "Enable full access for registry_events" on public.registry_events;
create policy "Enable full access for registry_events"
  on public.registry_events for all using (true) with check (true);

-- Privileges
grant usage on schema public to postgres, anon, authenticated, service_role;
